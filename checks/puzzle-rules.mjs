import assert from 'node:assert/strict';
import { benchPositionAllowed, cradleFits, frameFits, lampSurface, lampVisible, planeMatches, routeCollision, supportFits } from '../game/src/puzzles/rules.js';
import { createProgress } from '../game/src/progress.js';

const initial = [{ x: -1.13, z: 0.15, yaw: 0 }, { x: 0.43, z: 0.74, yaw: 0 }];
const moved = [{ x: -3.5, z: -0.2, yaw: Math.PI / 2 }, { x: -3.5, z: 1.6, yaw: Math.PI / 2 }];
assert.ok(routeCollision(initial) >= 0);
assert.equal(routeCollision(moved), -1);
assert.ok(benchPositionAllowed(moved[0], moved[1]));
assert.equal(benchPositionAllowed(moved[0], moved[0]), false);
assert.equal(benchPositionAllowed({ x: -4.4, z: 0, yaw: 0 }, moved[1]), false);
assert.ok(lampVisible({ x: 2.49, z: 1.19 }, true));
assert.equal(lampVisible({ x: -0.05, z: -1.87 }, true), false);
assert.equal(lampVisible({ x: 0.82, z: -2.63 }, true), false);
assert.equal(lampSurface({ x: 1.9, z: 1.19 }), undefined);
assert.equal(supportFits(0.08), false);
assert.ok(supportFits(0.52));
assert.equal(supportFits(1.2), false);
assert.ok(frameFits({ x: 0.36, z: -0.15, yaw: 0.08 }));
assert.equal(frameFits({ x: 0.3, z: -0.16, yaw: Math.PI }), false);
assert.ok(planeMatches({ x: 0.5, z: 0.1, yaw: 0.03 }, 0.13));
assert.equal(planeMatches({ x: 0.48, z: 0.08, yaw: 0 }, 0.071), false);
assert.equal(planeMatches({ x: 0.48, z: 0.08, yaw: Math.PI / 2 }, 0.13), false);
assert.ok(cradleFits({ x: 0.87, z: 0.1, yaw: 0.03 }));
assert.equal(cradleFits({ x: -0.83, z: 0.08, yaw: 0 }), false);

let storage;
globalThis.localStorage = { getItem: () => storage ?? null, setItem: (key, value) => { storage = value; } };
const ids = ['lin-benches', 'wang-photo', 'wang-support', 'wang-frame'];
const data = { objects: [], characters: [], dialogs: [], actions: ids.map((id) => ({ id })), scenes: [{ id: 'wang' }] };
const placement = [['bench-a', -3.5, 0, 1.6, Math.PI / 2, 0, true]];
const progress = createProgress(data, 'wang');
progress.record('lin-benches', placement);
assert.deepEqual(createProgress(data, 'wang').pose('lin-benches'), placement);
storage = JSON.stringify({ scene: 'wang', seen: ['wang-photo'], skipped: ['wang-frame'], poses: { 'wang-photo': [['bad', 0, null]] } });
const oldSave = createProgress(data, 'wang');
assert.ok(oldSave.skipped('wang-support'));
assert.equal(oldSave.pose('wang-photo'), undefined);
oldSave.restart();
assert.equal(createProgress(data, 'wang').has('wang-photo'), false);
assert.equal(createProgress(data, 'wang').pose('lin-benches'), undefined);
console.log('Puzzle geometry, valid alternatives, save restoration and legacy skip migration passed.');
